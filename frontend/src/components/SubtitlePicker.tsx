// ytdlp-studio:generated v1
import { AnalyzeService } from "../api";
import { useStore } from "../store";

export function SubtitlePicker() {
  const url = useStore((s) => s.url);
  const subs = useStore((s) => s.subs);
  const loading = useStore((s) => s.subsLoading);
  const options = useStore((s) => s.options);
  const set = useStore((s) => s.set);
  const patch = useStore((s) => s.patchOptions);

  const chosen = (options.subLangs || "").split(",").map((s) => s.trim()).filter(Boolean);

  async function load() {
    if (!url.trim()) return;
    set({ subsLoading: true, error: undefined });
    try {
      const info = await AnalyzeService.Subtitles(url.trim());
      set({ subs: info ?? undefined });
    } catch (e) {
      set({ error: String(e) });
    } finally {
      set({ subsLoading: false });
    }
  }

  function toggle(lang: string, auto: boolean) {
    const next = chosen.includes(lang) ? chosen.filter((l) => l !== lang) : [...chosen, lang];
    patch({ subLangs: next.join(","), subAutoGenerated: auto ? true : options.subAutoGenerated });
  }

  const manual = subs?.manual ?? [];
  const auto = subs?.auto ?? [];

  return (
    <section className="card subpicker">
      <div className="card-head">
        <h3>Altyazı dilleri</h3>
        <button className="btn small" disabled={loading || !url.trim()} onClick={() => void load()}>
          {loading ? "Listeleniyor…" : "Dilleri listele"}
        </button>
      </div>
      <div className="hint">Seçilenler: <code>{options.subLangs || "—"}</code></div>
      {manual.length > 0 && (
        <>
          <div className="sub-label">Manuel altyazılar</div>
          <div className="chips">
            {manual.map((t) => (
              <button key={t.lang} className={chosen.includes(t.lang) ? "chip on" : "chip"}
                onClick={() => toggle(t.lang, false)} title={(t.exts ?? []).join(", ")}>{t.lang}</button>
            ))}
          </div>
        </>
      )}
      {auto.length > 0 && (
        <>
          <div className="sub-label">Otomatik altyazılar</div>
          <div className="chips scroll">
            {auto.slice(0, 80).map((t) => (
              <button key={t.lang} className={chosen.includes(t.lang) ? "chip on" : "chip"}
                onClick={() => toggle(t.lang, true)}>{t.lang}</button>
            ))}
          </div>
        </>
      )}
      {subs && manual.length === 0 && auto.length === 0 && <div className="empty">Bu içerikte altyazı bulunamadı.</div>}
    </section>
  );
}
