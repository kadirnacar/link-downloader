var qualityRe = regexp.MustCompile("^(?:[0-9]|10|[0-9]+K)$")

var sbCats = map[string]bool{
	"sponsor": true, "intro": true, "outro": true, "selfpromo": true,
	"preview": true, "filler": true, "interaction": true, "music_offtopic": true,
	"poi_highlight": true, "chapter": true, "all": true,
}

func validSubFormat(f string) bool {
	switch f {
	case "", "best", "srt", "vtt", "ass", "lrc", "ttml":
		return true
	}
	return false
}

func validSB(list string) bool {
	if strings.TrimSpace(list) == "" {
		return true
	}
	for _, c := range strings.Split(list, ",") {
		if !sbCats[strings.TrimSpace(c)] {
			return false
		}
	}
	return true
}

func Validate(o DownloadOptions) error {
	switch o.Mode {
	case "audio":
		switch o.AudioFormat {
		case "mp3", "m4a", "opus", "flac", "wav", "aac", "vorbis":
		default:
			return fmt.Errorf("geçersiz ses formatı: %q", o.AudioFormat)
		}
		if !qualityRe.MatchString(o.AudioQuality) {
			return fmt.Errorf("geçersiz ses kalitesi: %q", o.AudioQuality)
		}
	case "video":
		switch o.VideoContainer {
		case "mp4", "mkv", "webm":
		default:
			return fmt.Errorf("geçersiz video kabı: %q", o.VideoContainer)
		}
		switch o.VideoHeight {
		case 0, 144, 240, 360, 480, 720, 1080, 1440, 2160, 4320:
		default:
			return fmt.Errorf("geçersiz çözünürlük: %d", o.VideoHeight)
		}
		switch o.VideoFPS {
		case 0, 24, 25, 30, 48, 50, 60:
		default:
			return fmt.Errorf("geçersiz FPS: %d", o.VideoFPS)
		}
	case "subtitle":
		if strings.TrimSpace(o.SubLangs) == "" {
			return errors.New("altyazı modu için en az bir dil girin")
		}
	default:
		return fmt.Errorf("geçersiz indirme tipi: %q", o.Mode)
	}

	if o.Mode == "subtitle" || o.SubtitlesEnabled {
		if strings.TrimSpace(o.SubLangs) == "" {
			return errors.New("altyazı dili boş olamaz")
		}
		if !validSubFormat(o.SubFormat) {
			return fmt.Errorf("geçersiz altyazı formatı: %q", o.SubFormat)
		}
	}
	if o.RemuxVideo != "" {
		switch o.RemuxVideo {
		case "mp4", "mkv", "webm":
		default:
			return fmt.Errorf("geçersiz remux hedefi: %q", o.RemuxVideo)
		}
	}
	if strings.TrimSpace(o.OutputDir) == "" {
		return errors.New("indirme klasörü seçilmedi")
	}
	if !strings.Contains(o.NameTemplate, ".%(ext)s") {
		return errors.New("dosya adı şablonu .%(ext)s içermeli")
	}
	if o.ConcurrentFragments < 1 || o.ConcurrentFragments > 16 {
		return errors.New("concurrentFragments 1-16 arası olmalı")
	}
	if o.Retries < 0 || o.Retries > 100 || o.FragmentRetries < 0 || o.FragmentRetries > 100 {
		return errors.New("retry değerleri 0-100 arası olmalı")
	}
	if o.SocketTimeout < 1 || o.SocketTimeout > 600 {
		return errors.New("socketTimeout 1-600 arası olmalı")
	}
	if o.SleepInterval < 0 || o.MaxSleepInterval < o.SleepInterval {
		return errors.New("maxSleepInterval, sleepInterval'dan küçük olamaz")
	}
	if o.ForceIPv4 && o.ForceIPv6 {
		return errors.New("IPv4 ve IPv6 aynı anda zorlanamaz")
	}
	if !validSB(o.SponsorblockRemove) || !validSB(o.SponsorblockMark) {
		return errors.New("geçersiz SponsorBlock kategorisi")
	}
	return nil
}
